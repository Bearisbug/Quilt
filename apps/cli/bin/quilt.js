#!/usr/bin/env node
// `npx quilt-canvas`（REQ-CORE-017）：准备 $QUILT_HOME（默认 ~/.quilt）→ 首次生成 config.env 密钥 → 起服务并打开浏览器。
// 用法：quilt [--home <dir>] [--port <n>] [--preview-port <n>] [--no-open]
import { mkdirSync, existsSync, writeFileSync, readFileSync, chmodSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import path from 'node:path';
import os from 'node:os';

const argv = process.argv.slice(2);
// 终端提示与 config.env 注释的语言（REQ-CORE-046）：命令行没有浏览器语言可跟，跟系统语言——LC_ALL → LC_MESSAGES → LANG，
// 都没设时看 Intl（Windows 走这条）；以 zh 开头为中文，其余英文
const sysLocale = process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG || Intl.DateTimeFormat().resolvedOptions().locale;
const t = (zh, en) => (/^zh/i.test(sysLocale) ? zh : en);
const opt = (name, def) => { const i = argv.indexOf(`--${name}`); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : def; };
if (argv.includes('--help') || argv.includes('-h')) {
  console.log(`quilt [--home <dir>] [--port <n>] [--preview-port <n>] [--no-open]\n  ${t('数据与密钥在 --home（默认 ~/.quilt）；再次运行同一目录即恢复全部项目。', 'Data and keys are kept in --home (default ~/.quilt); run again with the same directory to restore all projects.')}`);
  process.exit(0);
}
const major = Number(process.versions.node.split('.')[0]);
if (major < 22) { console.error(t(`Quilt 需要 Node.js 22 或更新（当前 ${process.versions.node}）`, `Quilt requires Node.js 22 or later (current: ${process.versions.node})`)); process.exit(1); }

const dist = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../dist');
const home = path.resolve(opt('home', process.env.QUILT_HOME || path.join(os.homedir(), '.quilt')));
// 目录 0700、config.env 0600（§15 本机密钥文件，v1.03）：里面有主密钥与 API Key，按默认 umask 落成 0755 / 0644 时
// 同机其他账号读得到。新建时按这个权限建，已有的（老版本建的）每次启动补一次 chmod
for (const d of ['', 'db', 'objects', 'agent']) mkdirSync(path.join(home, d), { recursive: true, mode: 0o700 });
try { chmodSync(home, 0o700); } catch { /* 目录不属于当前用户时改不了，照常启动 */ }

// 首次运行：生成两把随机密钥写进 config.env（用户以后可在这里改 LLM_DRIVER / API Key 等）
const cfgPath = path.join(home, 'config.env');
if (!existsSync(cfgPath)) {
  writeFileSync(cfgPath, [
    t('# Quilt 本机配置（由 quilt 首次启动生成）。改完重启 quilt 生效。', '# Quilt local config (generated by quilt on first start). Restart quilt for changes to take effect.'),
    `QUILT_SECRETS_KEY=${randomBytes(32).toString('base64')}`,
    `PREVIEW_SIGNING_SECRET=${randomBytes(32).toString('base64')}`,
    t('# 生成通道：agent-sdk = 本机 Claude 订阅（先在终端运行 claude 登录）| anthropic | gemini', '# Channel: agent-sdk = Local Claude subscription (run claude in a terminal to log in first) | anthropic | gemini'),
    'LLM_DRIVER=agent-sdk',
    'ANTHROPIC_API_KEY=',
    'GEMINI_API_KEY=',
    '',
  ].join('\n'), { mode: 0o600 });
  console.log(t(`[quilt] 首次运行：已初始化 ${home}`, `[quilt] First run: initialized ${home}`));
}
try { chmodSync(cfgPath, 0o600); } catch { /* 同上 */ }

const port = opt('port', process.env.API_PORT || '3100');
const previewPort = opt('preview-port', process.env.PREVIEW_PORT || '3101');
Object.assign(process.env, {
  QUILT_HOME: home,
  API_PORT: port,
  PREVIEW_PORT: previewPort,
  WEB_DIST: path.join(dist, 'web'),
  QUILT_MIGRATIONS_DIR: path.join(dist, 'drizzle'),
  QUILT_VENDOR_DIR: path.join(dist, 'vendor'),
  QUILT_VERSION: JSON.parse(readFileSync(path.join(dist, 'version.json'), 'utf8')).version,
  QUILT_OPEN_BROWSER: argv.includes('--no-open') ? '0' : '1',
});
process.on('SIGINT', () => { console.log('\n[quilt] bye'); process.exit(0); });
process.on('SIGTERM', () => process.exit(0));
await import(path.join(dist, 'server.mjs'));
